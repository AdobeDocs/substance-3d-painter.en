def collect_sbs_paths(root: str, recursive: bool) -> list[str]:
    root = os.path.normpath(root)
    paths: list[str] = []
    if not os.path.exists(root):
        return paths
    if os.path.isfile(root):
        if root.lower().endswith(".sbs"):
            return [root]
        return paths
    if not os.path.isdir(root):
        return paths
    if recursive:
        for dirpath, _, filenames in os.walk(root):
            for fn in filenames:
                if fn.lower().endswith(".sbs"):
                    paths.append(os.path.join(dirpath, fn))
    else:
        for fn in os.listdir(root):
            full = os.path.join(root, fn)
            if os.path.isfile(full) and fn.lower().endswith(".sbs"):
                paths.append(full)
    return sorted(paths)


def open_path_in_os(path: str) -> None:
    """Open a file or folder in the default app / file manager (best effort)."""
    path = os.path.normpath(os.path.abspath(path))
    if not os.path.exists(path):
        return
    try:
        if platform.system() == "Windows":
            os.startfile(path)  # type: ignore[attr-defined]
        elif sys.platform == "darwin":
            subprocess.run(["open", path], check=False)
        else:
            subprocess.run(["xdg-open", path], check=False)
    except OSError:
        pass


def parse_sbs(path: str, config: SBSDumpConfig):
    reader = SBSReader(path, config=config)
    return reader.Parse()


def run_export(
    paths: list[str],
    out_dir: str,
    config: SBSDumpConfig,
    write_html: bool,
    write_md: bool,
    autofill_path: str,
    log,
) -> tuple[int, int, dict[str, Any]]:
    ok = 0
    err = 0
    html_paths: list[str] = []
    md_paths: list[str] = []
    out_abs = os.path.abspath(out_dir)
    try:
        autofill = AutofillPreset.from_file(autofill_path)
    except Exception as e:
        log(f"Preset error ({autofill_path}): {e}")
        autofill = AutofillPreset.load_default()
    for path in paths:
        log(f"Processing: {path}")
        try:
            desc = parse_sbs(path, config)
        except Exception as e:
            log(f"  Error reading XML: {e}")
            err += 1
            continue
        if desc is None:
            log("  Skipped (could not parse).")
            err += 1
            continue
        graph_count = len(getattr(desc, "graphs", []) or [])
        if graph_count == 0:
            log(
                "  Skipped (0 graphs matched current filters). "
                "Try enabling 'Include graphs with an empty tag'."
            )
            err += 1
            continue
        try:
            if write_html:
                hd = HTMLDumper(p_writefolder=out_dir, p_config=config, p_autofill=autofill)
                html = hd.BuildHTML(desc)
                p = hd.WriteToFile(html)
                if p:
                    html_paths.append(p)
                elif html:
                    log("  Warning: HTML was built but not written (deprecated/empty filename?).")
                else:
                    log("  Warning: HTML build returned empty output.")
            if write_md:
                md = MarkdownDumper(p_writefolder=out_dir, p_config=config, p_autofill=autofill)
                text = md.BuildMarkdown(desc)
                p2 = md.WriteToFile(text)
                if p2:
                    md_paths.append(p2)
                elif text:
                    log("  Warning: Markdown was built but not written (deprecated/empty filename?).")
                else:
                    log("  Warning: Markdown build returned empty output.")
        except Exception as e:
            log(f"  Error writing output: {e}")
            err += 1
            continue
        ok += 1
        log("  Done.")
    artifacts: dict[str, Any] = {
        "out_dir": out_abs,
        "html_paths": html_paths,
        "md_paths": md_paths,
        "source_count": len(paths),
        "ok_count": ok,
    }
    return ok, err, artifacts


