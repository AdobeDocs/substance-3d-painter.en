class MarkdownFormatTab(ttk.Frame):
    """Edit the `markdown` section of the selected preset JSON (same file as Presets tab)."""

    def __init__(self, parent, app: "SBSParamDumperApp") -> None:
        super().__init__(parent, padding=8)
        self.app = app
        self._widgets: dict[str, tk.Widget] = {}

        ttk.Label(
            self,
            text="These templates control Markdown export only. They are stored in the preset file under “markdown”. "
            "Use the same preset on the Export tab. Literal braces: {{ and }}.",
            wraplength=680,
        ).pack(anchor="w", pady=(0, 8))

        toolbar = ttk.Frame(self)
        toolbar.pack(fill=tk.X, pady=(0, 8))
        ttk.Label(toolbar, text="Preset file:").pack(side=tk.LEFT)
        self.preset_combo = ttk.Combobox(
            toolbar,
            width=36,
            state="readonly",
            textvariable=self.app.selected_preset_var,
        )
        self.preset_combo.pack(side=tk.LEFT, padx=(8, 0))
        self.preset_combo.bind("<<ComboboxSelected>>", lambda _e: self.reload_from_file(quiet=True))
        ttk.Button(toolbar, text="Refresh list", command=self._refresh_preset_list).pack(side=tk.LEFT, padx=(8, 0))
        ttk.Button(toolbar, text="New preset…", command=self._new_preset).pack(side=tk.LEFT, padx=(8, 0))
        ttk.Button(toolbar, text="Save", command=self._save_full_preset).pack(side=tk.LEFT, padx=(8, 0))
        ttk.Button(toolbar, text="Save as…", command=self._save_full_preset_as).pack(side=tk.LEFT, padx=(8, 0))
        ttk.Button(toolbar, text="Reload from disk", command=self._reload_full_preset).pack(side=tk.LEFT, padx=(8, 0))

        canvas_wrap = ttk.Frame(self)
        canvas_wrap.pack(fill=tk.BOTH, expand=True)
        canvas = tk.Canvas(canvas_wrap, highlightthickness=0)
        scroll = ttk.Scrollbar(canvas_wrap, orient=tk.VERTICAL, command=canvas.yview)
        canvas.configure(yscrollcommand=scroll.set)
        inner = ttk.Frame(canvas)
        win_id = canvas.create_window((0, 0), window=inner, anchor="nw")

        def _on_inner_configure(_event=None) -> None:
            canvas.configure(scrollregion=canvas.bbox("all"))

        def _on_canvas_configure(event) -> None:
            canvas.itemconfigure(win_id, width=event.width)

        inner.bind("<Configure>", _on_inner_configure)
        canvas.bind("<Configure>", _on_canvas_configure)

        canvas.pack(side=tk.LEFT, fill=tk.BOTH, expand=True)
        scroll.pack(side=tk.RIGHT, fill=tk.Y)

        for group_title, fields in MARKDOWN_UI_GROUPS:
            lf = ttk.LabelFrame(inner, text=group_title, padding=8)
            lf.pack(fill=tk.X, pady=(0, 10))
            lf.columnconfigure(1, weight=1)
            gr = 0
            for key, desc in fields:
                ttk.Label(lf, text=desc, wraplength=200).grid(row=gr, column=0, sticky="nw", padx=(0, 8), pady=4)
                if key == "nested_indent":
                    e = ttk.Entry(lf, width=72)
                    e.grid(row=gr, column=1, sticky="ew", pady=4)
                    self._widgets[key] = e
                else:
                    tx = scrolledtext.ScrolledText(lf, height=2, width=72, wrap=tk.WORD, font=("TkFixedFont", 9))
                    tx.grid(row=gr, column=1, sticky="ew", pady=4)
                    self._widgets[key] = tx
                gr += 1

        self.reload_from_file(quiet=True)

    def _preset_json_path(self) -> str | None:
        pt = self.app.presets_tab
        d = pt.dir_var.get().strip()
        n = self.app.selected_preset_var.get().strip()
        if d and n:
            p = os.path.join(d, n)
            if os.path.isfile(p):
                return p
        return None

    def _refresh_preset_list(self) -> None:
        self.app.presets_tab.refresh_file_list()
        self.app._refresh_export_preset_combo()
        self.reload_from_file(quiet=True)

    def _ensure_selected_preset_loaded_in_editor(self) -> bool:
        path = self._preset_json_path()
        if not path:
            return False
        cur = self.app.presets_tab._current_file
        if not cur or os.path.abspath(cur) != os.path.abspath(path):
            self.app.presets_tab._load_path(path)
        return True

    def _new_preset(self) -> None:
        self.app.presets_tab._new_preset()
        self.reset_defaults()
        self.app._refresh_export_preset_combo()

    def _save_full_preset(self) -> None:
        if not self._ensure_selected_preset_loaded_in_editor():
            messagebox.showwarning("Markdown", "Choose a preset file first.")
            return
        self.app.presets_tab.flush_all_pending()
        self.app.presets_tab._edit["markdown"] = self._gather_dict()
        self.app.presets_tab._save()
        self.reload_from_file(quiet=True)
        self.app._refresh_export_preset_combo()

    def _save_full_preset_as(self) -> None:
        if not self._ensure_selected_preset_loaded_in_editor():
            # Create a new in-memory preset first if nothing is selected.
            self.app.presets_tab._blank_editor()
        self.app.presets_tab.flush_all_pending()
        self.app.presets_tab._edit["markdown"] = self._gather_dict()
        self.app.presets_tab._save_as()
        self.reload_from_file(quiet=True)
        self.app._refresh_export_preset_combo()

    def _reload_full_preset(self) -> None:
        self.app.presets_tab._reload()
        self.reload_from_file(quiet=True)

    def _set_widget_text(self, key: str, value: str) -> None:
        w = self._widgets[key]
        if isinstance(w, ttk.Entry):
            w.delete(0, tk.END)
            w.insert(0, value)
        else:
            w.delete("1.0", tk.END)
            w.insert("1.0", value)

    def _get_widget_text(self, key: str) -> str:
        w = self._widgets[key]
        if isinstance(w, ttk.Entry):
            return w.get().strip("\n")
        return w.get("1.0", "end").rstrip("\n")

    def _apply_dict(self, data: dict[str, str]) -> None:
        for key in self._widgets:
            self._set_widget_text(key, data.get(key, DEFAULT_MARKDOWN_FORMAT.get(key, "")))

    def reload_from_file(self, quiet: bool = False) -> None:
        path = self._preset_json_path()
        if not path:
            if not quiet:
                messagebox.showwarning("Markdown", "Choose a preset file on the Presets tab first.")
            self.reset_defaults()
            return
        try:
            with open(path, encoding="utf-8") as f:
                root = json.load(f)
        except (OSError, json.JSONDecodeError) as e:
            messagebox.showerror("Markdown", str(e))
            return
        md = root.get("markdown") if isinstance(root, dict) else None
        merged = merge_markdown_defaults(md if isinstance(md, dict) else None)
        self._apply_dict(merged)

    def reset_defaults(self) -> None:
        self._apply_dict(merge_markdown_defaults(None))

    def _gather_dict(self) -> dict[str, str]:
        return {key: self._get_widget_text(key) for key in self._widgets}

    def save_to_file(self) -> None:
        self.app.presets_tab.flush_all_pending()
        path = self._preset_json_path()
        if not path:
            messagebox.showwarning("Markdown", "Choose a preset file on the Presets tab first.")
            return
        try:
            with open(path, encoding="utf-8") as f:
                root = json.load(f)
        except (OSError, json.JSONDecodeError) as e:
            messagebox.showerror("Markdown", str(e))
            return
        if not isinstance(root, dict):
            messagebox.showerror("Markdown", "Preset file must be a JSON object.")
            return
        md = self._gather_dict()
        root["markdown"] = md
        try:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(root, f, indent=2, ensure_ascii=False)
        except OSError as e:
            messagebox.showerror("Markdown", str(e))
            return
        ap = os.path.abspath(path)
        if self.app.presets_tab._current_file and os.path.abspath(self.app.presets_tab._current_file) == ap:
            self.app.presets_tab._edit["markdown"] = md
        messagebox.showinfo("Markdown", f"Updated markdown section in:\n{path}")
        self.app._refresh_export_preset_combo()


